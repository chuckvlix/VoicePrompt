from typing import Literal
from pydantic import BaseModel, Field

ToneType = Literal["neutral", "formal", "concise", "email", "prompt"]


class TranscriptionResponse(BaseModel):
    text: str = Field(..., description="Transcribed text in Spanish")
    duration: float = Field(default=0.0, description="Duration in seconds of the processed audio")


class ImproveRequest(BaseModel):
    text: str = Field(..., min_length=1, description="Original text to improve")
    tone: ToneType = Field(default="neutral", description="Target tone for improvement")


class ImproveResponse(BaseModel):
    improved_text: str = Field(..., description="Refined text generated by the LLM")
    tone: ToneType = Field(..., description="Applied tone")


class HistoryCreateRequest(BaseModel):
    original_text: str = Field(..., min_length=1, description="Original transcribed or typed text")
    improved_text: str = Field(..., min_length=1, description="Improved version of the text")
    tone: ToneType = Field(..., description="Tone applied")


class HistoryItemResponse(BaseModel):
    id: int
    original_text: str
    improved_text: str
    tone: str
    created_at: str


class HistoryDeleteResponse(BaseModel):
    message: str
    id: int
